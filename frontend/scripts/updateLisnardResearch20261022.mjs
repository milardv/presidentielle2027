import { readFile } from 'node:fs/promises'
import { initializeApp, deleteApp } from 'firebase/app'
import { doc, getDoc, getFirestore, writeBatch } from 'firebase/firestore'
import { getFirebaseConfig } from './firebaseConfig.mjs'
import { lisnardResearch, lisnardVideos } from '../src/data/davidLisnardResearch20261022.js'

// Deliberately scoped to one candidate. Review with no argument; apply with --write.
const id = 'david-lisnard'
const apply = process.argv.includes('--write')
const tweets = JSON.parse(await readFile(new URL('./data/lisnardTweets20261022.json', import.meta.url), 'utf8'))
const app = initializeApp(getFirebaseConfig())
try {
  const db = getFirestore(app)
  const reference = doc(db, 'candidates_2027', id)
  const current = await getDoc(reference)
  if (!current.exists() || current.data().name !== 'David Lisnard') throw new Error('Unexpected candidate document')
  const interventions = [...lisnardResearch.interventions]
  const urls = new Set(interventions.map((entry) => entry.source.url))
  for (const existing of current.data().interventions ?? []) {
    if (!urls.has(existing.source?.url)) { interventions.push(existing); urls.add(existing.source?.url) }
  }
  const sources = [...lisnardResearch.sources]
  const sourceUrls = new Set(sources.map((entry) => entry.url))
  for (const existing of current.data().sources ?? []) {
    if (!sourceUrls.has(existing.url)) { sources.push(existing); sourceUrls.add(existing.url) }
  }
  for (const tweet of tweets) {
    if (tweet.candidateId !== id || tweet.authorUsername !== 'davidlisnard' || !/^https:\/\/x\.com\/davidlisnard\/status\/\d+$/.test(tweet.url)) throw new Error('Unexpected tweet provenance')
  }
  console.log(JSON.stringify({ mode: apply ? 'write' : 'dry-run', candidate: id, biographyParagraphs: lisnardResearch.biography.length, parcoursSteps: lisnardResearch.parcours.length, interventions: interventions.length, videos: lisnardVideos.length, tweets: tweets.length, sources: sources.length }, null, 2))
  if (apply) {
    const batch = writeBatch(db)
    batch.set(reference, { ...lisnardResearch, interventions, sources }, { merge: true })
    for (const video of lisnardVideos) {
      const entry = lisnardResearch.interventions.find((item) => item.id === `lisnard-youtube-${video.videoId}`)
      batch.set(doc(db, 'candidate_interventions_2027', `${id}-youtube-${video.videoId}`), {
        ...entry, candidateId: id, candidateName: 'David Lisnard', provider: 'youtube',
        providerData: { videoId: video.videoId, channelTitle: video.channel, thumbnailUrl: `https://i.ytimg.com/vi/${video.videoId}/hqdefault.jpg` },
        publishedAt: video.date, dataLastUpdated: '2026-10-22', autoGenerated: false,
        verificationSources: [video.reference],
      }, { merge: true })
    }
    for (const tweet of tweets) batch.set(doc(db, 'candidate_tweets_2027', `${id}-${tweet.id}`), tweet, { merge: true })
    await batch.commit()
    const saved = (await getDoc(reference)).data()
    if (saved.biography.length !== lisnardResearch.biography.length || saved.photoUrl !== current.data().photoUrl || saved.status !== current.data().status) throw new Error('Read-back verification failed')
    console.log('Saved and read back: biography, photo and candidacy verified.')
  }
} finally { await deleteApp(app) }
